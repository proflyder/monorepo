#!/usr/bin/env python3
"""Generates Kotlin ViewBinding classes from Android layout XML files.

rules_android has no ViewBinding support and the androidx.viewbinding artifact
is not part of the pinned Maven closure, so Bazel modules use this generator
(through `view_binding = True` in `metro_android_library`). The output mirrors
the AGP shape: `<LayoutName>Binding` in `<package>.databinding` with typed
`val`s per `android:id`, plus `inflate(...)` and `bind(...)`. Bindings
implement `dev.proflyder.home.core.ui.ViewBinding` instead of
`androidx.viewbinding.ViewBinding`.

Usage: gen_view_binding.py --package PKG --output FILE LAYOUT.xml...
"""

import argparse
import os
import re
import sys
import xml.etree.ElementTree as ET

ANDROID_NS = "{http://schemas.android.com/apk/res/android}"
VIEW_PACKAGE = {"View", "ViewStub", "SurfaceView", "TextureView", "ViewGroup"}
WEBKIT = {"WebView"}


def camel(name, upper_first):
    parts = [p for p in re.split(r"[_\W]+", name) if p]
    out = "".join(p[:1].upper() + p[1:] for p in parts)
    return out if upper_first else out[:1].lower() + out[1:]


def qualified(tag):
    if "." in tag:
        return tag
    if tag in VIEW_PACKAGE:
        return "android.view." + tag
    if tag in WEBKIT:
        return "android.webkit." + tag
    return "android.widget." + tag


def collect(root):
    """Returns (root_tag, [(id_name, tag)]) in document order, deduplicated."""
    views, seen = [], set()
    for element in root.iter():
        raw = element.get(ANDROID_NS + "id")
        if not raw or not (raw.startswith("@+id/") or raw.startswith("@id/")):
            continue
        name = raw.split("/", 1)[1]
        if name in seen:
            continue
        seen.add(name)
        tag = "View" if element.tag == "include" else element.tag
        views.append((name, tag))
    return root.tag, views


def render(package, layout_path):
    layout = os.path.splitext(os.path.basename(layout_path))[0]
    cls = camel(layout, True) + "Binding"
    root_tag, views = collect(ET.parse(layout_path).getroot())
    if root_tag == "merge":
        raise SystemExit(f"{layout_path}: <merge> roots are not supported")
    root_type = qualified(root_tag)

    taken = {"root"}
    props = []
    for name, tag in views:
        prop = camel(name, False)
        while prop in taken:
            prop += "View"
        taken.add(prop)
        props.append((prop, name, qualified(tag)))

    lines = [f"class {cls} private constructor("]
    lines.append(f"    override val root: {root_type},")
    for prop, _, typ in props:
        lines.append(f"    val {prop}: {typ},")
    lines.append(") : ViewBinding {")
    lines.append("    companion object {")
    lines.append("        fun inflate(")
    lines.append("            inflater: LayoutInflater,")
    lines.append("            parent: ViewGroup? = null,")
    lines.append("            attachToParent: Boolean = false,")
    lines.append(f"        ): {cls} {{")
    lines.append(f"            val root = inflater.inflate(R.layout.{layout}, parent, false)")
    lines.append("            if (attachToParent && parent != null) parent.addView(root)")
    lines.append("            return bind(root)")
    lines.append("        }")
    lines.append("")
    lines.append(f"        fun bind(view: View): {cls} = {cls}(")
    lines.append(f"            view as {root_type},")
    for prop, name, typ in props:
        lines.append(
            f'            view.findViewById<{typ}>(R.id.{name}) ?: error("Missing view @id/{name} in {layout}"),'
        )
    lines.append("        )")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--package", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("layouts", nargs="*")
    args = parser.parse_args()

    body = [render(args.package, p) for p in sorted(args.layouts)]
    header = [
        "// Generated by //platform/android:gen_view_binding. Do not edit.",
        "@file:Suppress(\"unused\")",
        "",
        f"package {args.package}.databinding",
        "",
        "import android.view.LayoutInflater",
        "import android.view.View",
        "import android.view.ViewGroup",
        "import dev.proflyder.home.core.ui.ViewBinding",
        f"import {args.package}.R",
        "",
    ]
    with open(args.output, "w", encoding="utf-8") as out:
        out.write("\n".join(header) + "\n" + "\n\n".join(body) + "\n")


if __name__ == "__main__":
    sys.exit(main())
