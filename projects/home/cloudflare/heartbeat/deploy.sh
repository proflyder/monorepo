#!/usr/bin/env bash
# Deploy the home heartbeat Worker from the reusable solutions/heartbeat source.
#
# Private values live in secrets/home/heartbeat.env (ignored by Git); the
# Cloudflare API token may instead live in secrets/home/cloudflare-workers.env
# (CLOUDFLARE_ENV_FILE), which is sourced first when present:
#
#   CLOUDFLARE_ACCOUNT_ID   Cloudflare account id
#   CLOUDFLARE_API_TOKEN    API token with Workers Scripts + KV edit
#   KV_NAMESPACE_ID         KV namespace bound as HEARTBEAT
#   PING_TOKEN              bearer token accepted by POST /ping
#   TELEGRAM_BOT_TOKEN      existing infra bot token
#   TELEGRAM_CHAT_ID        owner chat id
#   WORKER_NAME             optional, default home-heartbeat
#   GRACE_SECONDS           optional, default 900
#   REMIND_SECONDS          optional, default 21600 (0 disables)
#   SITE_NAME               optional, default "дом"
#
# Usage:
#   ./deploy.sh             render config and deploy
#   ./deploy.sh --secrets   push the three Worker secrets (stdin, never echoed)
#
# This script does not create the KV namespace, DNS route or Cloudflare token.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"
ENV_FILE="${HEARTBEAT_ENV_FILE:-$ROOT/secrets/home/heartbeat.env}"
CLOUDFLARE_ENV_FILE="${CLOUDFLARE_ENV_FILE:-$ROOT/secrets/home/cloudflare-workers.env}"
GENERATED="$ROOT/projects/home/cloudflare/heartbeat/wrangler.generated.toml"
WRANGLER_VERSION="4.156.1"

PUSH_SECRETS=0

die() {
  echo "error: $*" >&2
  exit 1
}

usage() {
  sed -n '2,25p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

for argument in "$@"; do
  case "$argument" in
    --secrets) PUSH_SECRETS=1 ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $argument (use --secrets or --help)" ;;
  esac
done

[[ -f "$ENV_FILE" ]] || die "private env file not found: $ENV_FILE"
[[ -r "$ENV_FILE" ]] || die "private env file is not readable: $ENV_FILE"

set -a
if [[ -r "$CLOUDFLARE_ENV_FILE" ]]; then
  # shellcheck source=/dev/null
  . "$CLOUDFLARE_ENV_FILE"
fi
# shellcheck source=/dev/null
. "$ENV_FILE"
set +a

: "${CLOUDFLARE_API_TOKEN:?CLOUDFLARE_API_TOKEN is required}"
WORKER_NAME="${WORKER_NAME:-home-heartbeat}"
GRACE_SECONDS="${GRACE_SECONDS:-900}"
REMIND_SECONDS="${REMIND_SECONDS:-21600}"
SITE_NAME="${SITE_NAME:-дом}"

[[ "${CLOUDFLARE_ACCOUNT_ID:-}" =~ ^[0-9a-f]{32}$ ]] \
  || die "CLOUDFLARE_ACCOUNT_ID must be a 32-character lowercase hex id"
[[ "${KV_NAMESPACE_ID:-}" =~ ^[0-9a-f]{32}$ ]] \
  || die "KV_NAMESPACE_ID must be a 32-character lowercase hex id"
[[ "$WORKER_NAME" =~ ^[a-z0-9][a-z0-9-]{0,62}$ ]] \
  || die "WORKER_NAME must be a Cloudflare Worker name (lowercase letters, digits, dashes)"
[[ "$GRACE_SECONDS" =~ ^[0-9]+$ ]] || die "GRACE_SECONDS must be a non-negative integer"
[[ "$REMIND_SECONDS" =~ ^[0-9]+$ ]] || die "REMIND_SECONDS must be a non-negative integer"
[[ "$SITE_NAME" != *'"'* && "$SITE_NAME" != *'\'* && "$SITE_NAME" != *$'\n'* ]] \
  || die "SITE_NAME must not contain quotes, backslashes or newlines"

# The rendered file carries private account/namespace ids (no secrets). It is
# git-ignored and removed on exit.
cleanup() {
  rm -f "$GENERATED"
}
trap cleanup EXIT

cat > "$GENERATED" <<EOF
# Generated by deploy.sh. Private ids; never commit.
name = "$WORKER_NAME"
main = "../../../../solutions/heartbeat/src/worker.js"
compatibility_date = "2025-11-01"
workers_dev = true
account_id = "$CLOUDFLARE_ACCOUNT_ID"

[triggers]
crons = ["*/5 * * * *"]

[[kv_namespaces]]
binding = "HEARTBEAT"
id = "$KV_NAMESPACE_ID"

[vars]
GRACE_SECONDS = "$GRACE_SECONDS"
REMIND_SECONDS = "$REMIND_SECONDS"
SITE_NAME = "$SITE_NAME"
EOF

WRANGLER=(npx --yes "wrangler@$WRANGLER_VERSION")

if [[ "$PUSH_SECRETS" == 1 ]]; then
  push_secret() {
    local name="$1"
    local value="${!name:-}"
    [[ -n "$value" ]] || die "missing $name in $ENV_FILE"
    # Value goes through stdin only; it is never printed or passed as an argv.
    printf '%s' "$value" | "${WRANGLER[@]}" secret put "$name" \
      --name "$WORKER_NAME" --config "$GENERATED" >/dev/null
    echo "updated Worker secret: $name"
  }

  push_secret PING_TOKEN
  push_secret TELEGRAM_BOT_TOKEN
  push_secret TELEGRAM_CHAT_ID
  exit 0
fi

"${WRANGLER[@]}" deploy --config "$GENERATED"
