// updateExport regenerates the committed v1 SQL dump. It is deliberately
// opt-in: normal `go test` runs skip it so the repository stays read-only.
var updateExport = flag.Bool("update-export", false, "regenerate testdata/go_v1.sql")

// TestExportGoDatabase creates a database with the Go store (the rollback
// reference) and writes a textual SQL dump. The Rust store test loads that
// dump and must read the same rows, proving schema and column compatibility
// without committing a binary database.
func TestExportGoDatabase(t *testing.T) {
	if !*updateExport {
		t.Skip("run with -update-export to regenerate solutions/scheduler/testdata/go_v1.sql")
	}
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "go-v1.db")
	cfg := DefaultConfig()
	cfg.MaxAttempts = 2
	st, err := Open(ctx, path, cfg)
	if err != nil {
		t.Fatalf("open store: %v", err)
	}
	now := time.Unix(1767268800, 0).UTC()

	alarm := &ricardov1.Schedule{
		Label:    "wake",
		Kind:     ricardov1.ScheduleKind_SCHEDULE_KIND_ALARM,
		Timezone: "UTC",
		At:       &ricardov1.WallTime{Hour: 7, Minute: 30},
		Repeat:   ricardov1.RepeatKind_REPEAT_KIND_DAILY,
		Enabled:  true,
	}
	if _, err := st.CreateSchedule(ctx, alarm, "sched-key", now); err != nil {
		t.Fatalf("create alarm: %v", err)
	}
	reminder := &ricardov1.Schedule{
		Label:    "call mom",
		Kind:     ricardov1.ScheduleKind_SCHEDULE_KIND_REMINDER,
		Timezone: "UTC",
		At:       &ricardov1.WallTime{Hour: 9},
		OnceDate: "2026-02-01",
		Repeat:   ricardov1.RepeatKind_REPEAT_KIND_ONCE,
		Enabled:  true,
	}
	if _, err := st.CreateSchedule(ctx, reminder, "", now); err != nil {
		t.Fatalf("create reminder: %v", err)
	}
	scenario := &ricardov1.Schedule{
		Label:    "evening",
		Kind:     ricardov1.ScheduleKind_SCHEDULE_KIND_SCENARIO,
		Timezone: "Europe/Berlin",
		At:       &ricardov1.WallTime{Hour: 20, Minute: 15},
		Repeat:   ricardov1.RepeatKind_REPEAT_KIND_DAILY,
		Enabled:  false,
	}
	if _, err := st.CreateSchedule(ctx, scenario, "", now); err != nil {
		t.Fatalf("create scenario: %v", err)
	}

	tea, err := st.StartTimer(ctx, "tea", 300, "timer-key", now)
	if err != nil {
		t.Fatalf("start tea: %v", err)
	}
	if _, err := st.PauseTimer(ctx, tea.GetId(), time.Unix(now.Unix()+100, 0).UTC()); err != nil {
		t.Fatalf("pause tea: %v", err)
	}
	if _, err := st.StartTimer(ctx, "coffee", 600, "", now); err != nil {
		t.Fatalf("start coffee: %v", err)
	}

	if _, err := st.EnqueueTask(ctx, "notify.push", "", "", 0, "task-key", now); err != nil {
		t.Fatalf("enqueue notify: %v", err)
	}
	if _, err := st.EnqueueTask(ctx, "demo.run", `{"x":1}`, "voice-work", now.Unix()+60, "", now); err != nil {
		t.Fatalf("enqueue demo: %v", err)
	}

	events, err := st.ListDueEvents(ctx, "home-1", 60, 50, "", now)
	if err != nil {
		t.Fatalf("lease events: %v", err)
	}
	for _, event := range events {
		if event.GetTaskType() == "notify.push" {
			if _, err := st.AckEvent(ctx, event.GetId(), "home-1",
				ricardov1.AckOutcome_ACK_OUTCOME_DELIVERED, "ok", now); err != nil {
				t.Fatalf("ack notify: %v", err)
			}
		}
	}
	if _, err := st.Tick(ctx, time.Unix(now.Unix()+600, 0).UTC()); err != nil {
		t.Fatalf("tick coffee: %v", err)
	}
	if _, err := st.Tick(ctx, time.Unix(1767339000, 0).UTC()); err != nil {
		t.Fatalf("tick alarm: %v", err)
	}
	if err := st.Close(); err != nil {
		t.Fatalf("close store: %v", err)
	}

	dump, err := dumpDatabase(path)
	if err != nil {
		t.Fatalf("dump database: %v", err)
	}
	target := filepath.Join("..", "..", "testdata", "go_v1.sql")
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatalf("create testdata: %v", err)
	}
	if err := os.WriteFile(target, []byte(dump), 0o644); err != nil {
		t.Fatalf("write dump: %v", err)
	}
	t.Logf("wrote %s (%d bytes)", target, len(dump))
}

func dumpDatabase(path string) (string, error) {
	db, err := sql.Open("sqlite", path)
	if err != nil {
		return "", err
	}
	defer func() { _ = db.Close() }()

	var buffer strings.Builder
	buffer.WriteString("-- Generated by TestExportGoDatabase; do not edit by hand.\n")
	for _, kind := range []string{"table", "index"} {
		rows, err := db.Query(
			`SELECT sql FROM sqlite_master WHERE type = ? AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid`,
			kind)
		if err != nil {
			return "", err
		}
		for rows.Next() {
			var statement string
			if err := rows.Scan(&statement); err != nil {
				_ = rows.Close()
				return "", err
			}
			statement = strings.Replace(statement, "CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
			statement = strings.Replace(statement, "CREATE INDEX ", "CREATE INDEX IF NOT EXISTS ", 1)
			buffer.WriteString(statement)
			buffer.WriteString(";\n")
		}
		if err := rows.Err(); err != nil {
			_ = rows.Close()
			return "", err
		}
		_ = rows.Close()
	}
	for _, table := range []string{"schema_meta", "schedules", "timers", "events", "idempotency", "consumers"} {
		if err := dumpTable(&buffer, db, table); err != nil {
			return "", err
		}
	}
	return buffer.String(), nil
}

func dumpTable(buffer *strings.Builder, db *sql.DB, table string) error {
	rows, err := db.Query("SELECT * FROM " + table)
	if err != nil {
		return err
	}
	defer func() { _ = rows.Close() }()
	columns, err := rows.Columns()
	if err != nil {
		return err
	}
	for rows.Next() {
		values := make([]any, len(columns))
		pointers := make([]any, len(columns))
		for index := range values {
			pointers[index] = &values[index]
		}
		if err := rows.Scan(pointers...); err != nil {
			return err
		}
		quoted := make([]string, len(values))
		for index, value := range values {
			quoted[index] = sqlLiteral(value)
		}
		fmt.Fprintf(buffer, "INSERT INTO %s (%s) VALUES (%s);\n",
			table, strings.Join(columns, ", "), strings.Join(quoted, ", "))
	}
	return rows.Err()
}

func sqlLiteral(value any) string {
	switch typed := value.(type) {
	case nil:
		return "NULL"
	case string:
		return "'" + strings.ReplaceAll(typed, "'", "''") + "'"
	case []byte:
		return "'" + strings.ReplaceAll(string(typed), "'", "''") + "'"
	default:
		return fmt.Sprintf("%v", typed)
	}
}
