//! Home Assistant executor for the durable scheduler.
//!
//! The bridge leases the configured queue, maps an allowlisted
//! `(source kind, action)` pair to one configured HA script, records a local
//! receipt and only then acknowledges the event. It owns no schedule state and
//! has no inbound listener.
//!
//! The crate mirrors the former Go `ha-bridge` binary:
//!
//! * [`config`] reads the same environment with the same defaults and the
//!   same file-first secret priority;
//! * [`domain`] is the pure plan/order/stop/announce decision table;
//! * [`ledger`] is the version-1 JSON receipt file with atomic writes;
//! * [`bridge`] is the [`home_worker::Handler`] that turns a plan into an HA
//!   call and a terminal ack;
//! * [`app`] and [`health`] compose the process and the distroless probe.
//!
//! `solutions/ha-bridge/testdata` holds the golden vectors generated by the Go
//! tests; the Rust tests read the same files.

#![deny(missing_debug_implementations)]

pub mod app;
pub mod bridge;
pub mod config;
pub mod domain;
pub mod health;
pub mod ledger;
