const schemaPath = "../../../../solutions/currency-bot/testdata/store/schema_v1.sql"

type schemaRow struct {
	Timestamp time.Time
	USDBuy    float64
	USDSell   float64
	RUBBuy    float64
	RUBSell   float64
}

var schemaRecords = []schemaRow{
	{Timestamp: time.Date(2026, 10, 31, 12, 0, 0, 0, time.UTC), USDBuy: 500.1, USDSell: 501.2, RUBBuy: 5.05, RUBSell: 5.15},
	{Timestamp: time.Date(2026, 10, 31, 11, 0, 0, 0, time.UTC), USDBuy: 499.5, USDSell: 500.25, RUBBuy: 4.99, RUBSell: 5.09},
	{Timestamp: time.Date(2026, 10, 30, 12, 0, 0, 0, time.UTC), USDBuy: 498, USDSell: 499, RUBBuy: 4.95, RUBSell: 5.05},
}

var schemaSent = []model.SentAlert{
	{
		Key:   model.AlertKey{Pair: model.USDToKZT, Period: "HOUR", RateType: model.Sell},
		Level: model.Warning, Direction: model.Up,
		RateAtAlert: 501.2, ChangePercent: 0.6,
	},
	{
		Key:   model.AlertKey{Pair: model.RUBToKZT, Period: "DAY", RateType: model.Buy},
		Level: model.Critical, Direction: model.Down,
		RateAtAlert: 4.95, ChangePercent: -2.1,
	},
}

func schemaNumbers(value float64) string {
	return strconv.FormatFloat(value, 'g', -1, 64)
}

func dumpSchema(t *testing.T) string {
	t.Helper()
	st, err := Open(context.Background(), filepath.Join(t.TempDir(), "dump.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = st.Close() }()
	for _, row := range schemaRecords {
		record := model.Record{Timestamp: row.Timestamp, Rates: model.Rates{
			USDToKZT: model.ExchangeRate{Buy: row.USDBuy, Sell: row.USDSell},
			RUBToKZT: model.ExchangeRate{Buy: row.RUBBuy, Sell: row.RUBSell},
		}}
		if _, err := st.SaveRecord(context.Background(), record); err != nil {
			t.Fatal(err)
		}
	}
	for _, alert := range schemaSent {
		if err := st.RecordSentAlert(context.Background(), alert); err != nil {
			t.Fatal(err)
		}
	}

	var out strings.Builder
	out.WriteString("-- currency-bot SQLite schema v1 with sample rows.\n")
	out.WriteString("-- Generated by `go test ./solutions/currency-bot/internal/store -run TestSchemaV1Dump -update`.\n")
	out.WriteString("-- The Go store and its Rust replacement must open this file unchanged.\n\n")
	out.WriteString(strings.TrimSpace(schema))
	out.WriteString("\n\n")

	rows, err := st.db.Query(`SELECT id, timestamp, usd_buy, usd_sell, rub_buy, rub_sell FROM currency_history ORDER BY id`)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	for rows.Next() {
		var id, timestamp int64
		var usdBuy, usdSell, rubBuy, rubSell float64
		if err := rows.Scan(&id, &timestamp, &usdBuy, &usdSell, &rubBuy, &rubSell); err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&out, "INSERT INTO currency_history (id, timestamp, usd_buy, usd_sell, rub_buy, rub_sell) VALUES (%d, %d, %s, %s, %s, %s);\n",
			id, timestamp, schemaNumbers(usdBuy), schemaNumbers(usdSell), schemaNumbers(rubBuy), schemaNumbers(rubSell))
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}

	out.WriteString("\n")
	alertRows, err := st.db.Query(`SELECT id, pair, period, rate_type, level, direction, rate_at_alert, change_percent FROM sent_alerts ORDER BY id`)
	if err != nil {
		t.Fatal(err)
	}
	defer alertRows.Close()
	for alertRows.Next() {
		var (
			id                                       int64
			pair, period, rateType, level, direction string
			rateAtAlert, changePercent               float64
		)
		if err := alertRows.Scan(&id, &pair, &period, &rateType, &level, &direction, &rateAtAlert, &changePercent); err != nil {
			t.Fatal(err)
		}
		fmt.Fprintf(&out, "INSERT INTO sent_alerts (id, pair, period, rate_type, level, direction, rate_at_alert, change_percent) VALUES (%d, '%s', '%s', '%s', '%s', '%s', %s, %s);\n",
			id, pair, period, rateType, level, direction, schemaNumbers(rateAtAlert), schemaNumbers(changePercent))
	}
	if err := alertRows.Err(); err != nil {
		t.Fatal(err)
	}
	return out.String()
}

func TestSchemaV1Dump(t *testing.T) {
	golden.RunText(t, *updateGolden, schemaPath, dumpSchema(t))
}

func TestSchemaV1IsReadable(t *testing.T) {
	raw, err := os.ReadFile(golden.Resolve(t, schemaPath))
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "schema.db")
	db, err := sql.Open("sqlite", "file:"+path)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(string(raw)); err != nil {
		_ = db.Close()
		t.Fatalf("execute schema dump: %v", err)
	}
	if err := db.Close(); err != nil {
		t.Fatal(err)
	}

	st, err := Open(context.Background(), path)
	if err != nil {
		t.Fatalf("open dump with the store: %v", err)
	}
	defer func() { _ = st.Close() }()

	count, err := st.CountRecords(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if count != len(schemaRecords) {
		t.Fatalf("records = %d, want %d", count, len(schemaRecords))
	}
	latest, err := st.LatestRecord(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if latest.Rates.USDToKZT.Sell != 501.2 || latest.Rates.RUBToKZT.Buy != 5.05 {
		t.Fatalf("latest rates did not survive the dump: %+v", latest.Rates)
	}
	sentCount, err := st.CountSentAlerts(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if sentCount != len(schemaSent) {
		t.Fatalf("sent alerts = %d, want %d", sentCount, len(schemaSent))
	}
	// A dump without sqlite_sequence must keep AUTOINCREMENT usable.
	if _, err := st.SaveRecord(context.Background(), model.Record{
		Timestamp: time.Date(2026, 11, 1, 0, 0, 0, 0, time.UTC),
		Rates:     model.Rates{USDToKZT: model.ExchangeRate{Buy: 1, Sell: 2}, RUBToKZT: model.ExchangeRate{Buy: 3, Sell: 4}},
	}); err != nil {
		t.Fatalf("insert after loading the dump: %v", err)
	}
}
